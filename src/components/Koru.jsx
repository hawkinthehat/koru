export function Koru(props) {
  const { nodes, materials } = useGLTF('/Koru.glb')
  const bodyRef = useRef(null)
  const interactionTarget = useRef(0)
  const baseBodyScale = useRef(null)
  const baseHeadRotation = useRef(null)
  const materialFallback = useMemo(() => Object.values(materials ?? {})[0] ?? null, [materials])
  const bumpNoiseTexture = useMemo(() => createNoiseTexture(), [])
  const meshNodes = useMemo(() => {
    return Object.values(nodes).filter((node) => node?.isMesh)
  }, [nodes])
  const meshDescriptors = useMemo(() => {
    return meshNodes.map((node) => ({
      key: node.uuid,
      name: node.name,
      geometry: node.geometry,
      position: node.position.toArray(),
      rotation: [node.rotation.x, node.rotation.y, node.rotation.z],
      scale: node.scale.toArray(),
    }))
  }, [meshNodes])
  const roleCounts = useMemo(() => {
    return meshDescriptors.reduce(
      (accumulator, mesh) => {
        const role = classifyMeshRole(mesh.name)
        accumulator[role] += 1
        return accumulator
      },
      { fur: 0, mask: 0, accent: 0, eyes: 0 },
    )
  }, [meshDescriptors])
  const needsProceduralPaletteFallback = roleCounts.mask === 0 || roleCounts.accent === 0
  const needsProceduralEyeFallback = roleCounts.eyes === 0

  const furMaterial = useMemo(() => {
    const sourceMaterial = materialFallback?.isMeshStandardMaterial
      ? materialFallback.clone()
      : new MeshStandardMaterial()

    sourceMaterial.name = 'KoruFurMaterial'
    sourceMaterial.color.set(PALETTE.fur)
    applySoftFurFinish(sourceMaterial, bumpNoiseTexture)

    if (needsProceduralPaletteFallback) {
      applyProceduralPaletteFallback(sourceMaterial)
    }

    sourceMaterial.needsUpdate = true
    return sourceMaterial
  }, [bumpNoiseTexture, materialFallback, needsProceduralPaletteFallback])

  const maskMaterial = useMemo(() => {
    const sourceMaterial = furMaterial.clone()
    sourceMaterial.name = 'KoruFacialMaskMaterial'
    sourceMaterial.color.set(PALETTE.mask)
    sourceMaterial.needsUpdate = true
    return sourceMaterial
  }, [furMaterial])

  const accentMaterial = useMemo(() => {
    const sourceMaterial = furMaterial.clone()
    sourceMaterial.name = 'KoruAccentMaterial'
    sourceMaterial.color.set(PALETTE.accent)
    sourceMaterial.needsUpdate = true
    return sourceMaterial
  }, [furMaterial])

  const eyeMaterial = useMemo(() => {
    const sourceMaterial = new MeshPhysicalMaterial()
    sourceMaterial.name = 'KoruEyeMaterial'
    sourceMaterial.color.set(PALETTE.eyes)
    sourceMaterial.clearcoat = 1
    sourceMaterial.clearcoatRoughness = 0.06
    sourceMaterial.roughness = 0.1
    sourceMaterial.metalness = 0.05
    sourceMaterial.bumpMap = bumpNoiseTexture
    sourceMaterial.bumpScale = 0.004
    sourceMaterial.envMapIntensity = 1.3
    sourceMaterial.needsUpdate = true
    return sourceMaterial
  }, [bumpNoiseTexture])

  const proceduralEyeMaterial = useMemo(() => {
    if (!needsProceduralEyeFallback) {
      return null
    }

    const sourceMaterial = new MeshPhysicalMaterial({
      color: PALETTE.eyes,
      transparent: true,
      depthWrite: false,
      clearcoat: 1,
      clearcoatRoughness: 0.04,
      roughness: 0.1,
      metalness: 0.05,
      envMapIntensity: 1.4,
      bumpMap: bumpNoiseTexture,
      bumpScale: 0.004,
    })
    sourceMaterial.name = 'KoruProceduralEyeOverlayMaterial'
    applyProceduralEyeMask(sourceMaterial)
    sourceMaterial.needsUpdate = true
    return sourceMaterial
  }, [bumpNoiseTexture, needsProceduralEyeFallback])

  useEffect(() => {
    return () => {
      furMaterial.dispose()
      maskMaterial.dispose()
      accentMaterial.dispose()
      eyeMaterial.dispose()
      proceduralEyeMaterial?.dispose()
      bumpNoiseTexture.dispose()
    }
  }, [accentMaterial, bumpNoiseTexture, eyeMaterial, furMaterial, maskMaterial, proceduralEyeMaterial])

  const headBone = useMemo(() => {
    const graphNodes = Object.values(nodes)
    const directBoneMatch = graphNodes.find((node) => {
      return node?.isBone && /head|neck|skull/i.test(node.name)
    })

    if (directBoneMatch) {
      return directBoneMatch
    }

    const skeletonBoneMatch = graphNodes
      .filter((node) => node?.isSkinnedMesh && node.skeleton?.bones?.length)
      .flatMap((node) => node.skeleton.bones)
      .find((bone) => /head|neck|skull/i.test(bone.name))

    return skeletonBoneMatch ?? null
  }, [nodes])

  useFrame(({ clock, pointer }, delta) => {
    const phase = clock.elapsedTime % BREATH_CYCLE_SECONDS
    const breathPulse = getBreathPulse(phase)
    const body = bodyRef.current

    if (body) {
      if (!baseBodyScale.current) {
        baseBodyScale.current = body.scale.clone()
      }
      const targetScale = 1 + breathPulse * BREATH_AMPLITUDE
      const easing = 1 - Math.exp(-4 * delta)
      body.scale.x = MathUtils.lerp(body.scale.x, baseBodyScale.current.x * targetScale, easing)
      body.scale.y = MathUtils.lerp(body.scale.y, baseBodyScale.current.y * targetScale, easing)
      body.scale.z = MathUtils.lerp(body.scale.z, baseBodyScale.current.z * targetScale, easing)
    }

    if (headBone) {
      if (!baseHeadRotation.current) {
        baseHeadRotation.current = {
          x: headBone.rotation.x,
          y: headBone.rotation.y,
        }
      }

      const targetYaw = MathUtils.clamp(pointer.x, -1, 1) * HEAD_TILT_RADIANS * interactionTarget.current
      const targetPitch =
        MathUtils.clamp(-pointer.y, -1, 1) * HEAD_TILT_RADIANS * 0.6 * interactionTarget.current
      const tiltEasing = 1 - Math.exp(-8 * delta)
      headBone.rotation.y = MathUtils.lerp(
        headBone.rotation.y,
        baseHeadRotation.current.y + targetYaw,
        tiltEasing,
      )
      headBone.rotation.x = MathUtils.lerp(
        headBone.rotation.x,
        baseHeadRotation.current.x + targetPitch,
        tiltEasing,
      )
    }
  })

  const setInteracting = (value) => {
    interactionTarget.current = value
  }

  return (
    <group
      {...props}
      dispose={null}
      onPointerOver={(event) => {
        event.stopPropagation()
        setInteracting(1)
      }}
      onPointerOut={() => setInteracting(0)}
      onPointerDown={(event) => {
        event.stopPropagation()
        setInteracting(1)
      }}
      onPointerUp={() => setInteracting(0)}
    >
      <group ref={bodyRef}>
        {meshDescriptors.map((mesh) => {
          const role = classifyMeshRole(mesh.name)
          const materialForMesh =
            role === 'eyes'
              ? eyeMaterial
              : role === 'mask'
                ? maskMaterial
                : role === 'accent'
                  ? accentMaterial
                  : furMaterial

          return (
            <mesh
              key={mesh.key}
              name={mesh.name}
              geometry={mesh.geometry}
              position={mesh.position}
              rotation={mesh.rotation}
              scale={mesh.scale}
              material={materialForMesh}
              castShadow
              receiveShadow
            />
          )
        })}
        {needsProceduralEyeFallback &&
          proceduralEyeMaterial &&
          meshDescriptors.map((mesh) => (
            <mesh
              key={`${mesh.key}-eye-overlay`}
              name={`${mesh.name}-eye-overlay`}
              geometry={mesh.geometry}
              position={mesh.position}
              rotation={mesh.rotation}
              scale={mesh.scale}
              material={proceduralEyeMaterial}
              renderOrder={2}
              frustumCulled={false}
            />
          ))}
      </group>
    </group>
  )
}

